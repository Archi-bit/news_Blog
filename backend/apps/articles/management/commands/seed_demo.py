class Command(BaseCommand):
    help = "Создать локальные демонстрационные данные без дубликатов"

    def handle(self, *args, **options):
        if not settings.DEMO_MODE or not settings.DEBUG:
            raise CommandError(
                "seed_demo разрешён только при DEMO_MODE=True и DJANGO_DEBUG=True"
            )
        with transaction.atomic():
            users = []
            for i, name in enumerate(["Анна", "Тимур", "Мария", "Алексей", "Алина"], 1):
                user, created = UserProfile.objects.get_or_create(
                    username=f"demo{i}",
                    defaults={
                        "first_name": name,
                        "email": f"demo{i}@example.com",
                        "bio": "Пишу о науке, технологиях и жизни города.",
                    },
                )
                if created:
                    user.set_password("DemoNews!2026")
                    user.save()
                users.append(user)
            admin, created = UserProfile.objects.get_or_create(
                username="demo_admin",
                defaults={
                    "is_staff": True,
                    "is_superuser": True,
                    "email": "admin@example.com",
                },
            )
            if created:
                admin.set_password("AdminNews!2026")
                admin.save()
            tags = [
                Tag.objects.get_or_create(name=name)[0]
                for name in [
                    "Python",
                    "Django",
                    "React",
                    "AI",
                    "Football",
                    "Space",
                    "Startup",
                    "Education",
                    "Technology",
                    "Programming",
                ]
            ]
            articles = []
            for index, (category_name, titles, content) in enumerate(TOPICS):
                category, _ = Category.objects.get_or_create(name=category_name)
                for j, title in enumerate(titles):
                    number = index * 4 + j
                    article, created = Article.objects.get_or_create(
                        title=title,
                        author=users[number % 5],
                        defaults={
                            "category": category,
                            "content": content,
                            "excerpt": content.split(". ")[0] + ".",
                            "is_published": j != 3,
                        },
                    )
                    if created:
                        article.tags.set([tags[number % 10], tags[(number + 3) % 10]])
                    if not article.thumbnail:
                        picture = Image.new(
                            "RGB", (960, 540), (30 + index * 30, 80 + j * 25, 140)
                        )
                        draw = ImageDraw.Draw(picture)
                        draw.rectangle((80, 100, 880, 440), outline="white", width=6)
                        draw.text(
                            (110, 240), f"NEWS BLOG / {number + 1:02}", fill="white"
                        )
                        output = BytesIO()
                        picture.save(output, format="PNG")
                        article.thumbnail.save(
                            f"demo-{number + 1}.png",
                            ContentFile(output.getvalue()),
                            save=True,
                        )
                    articles.append(article)
            published = [a for a in articles if a.is_published]
            for i in range(30):
                Comment.objects.get_or_create(
                    article=published[i % 15],
                    author=users[i % 5],
                    text=[
                        "Спасибо за понятное объяснение! Хочу попробовать этот подход в своём проекте.",
                        "Интересный пример. Будет полезно обсудить его на следующей встрече.",
                    ][i // 15],
                )
            for i in range(40):
                Like.objects.get_or_create(
                    article=published[i % 15], user=users[(i // 15 + i) % 5]
                )
            for i, user in enumerate(users):
                for offset in [1, 2, 3]:
                    Follow.objects.get_or_create(
                        follower=user, following=users[(i + offset) % 5]
                    )
        self.stdout.write(
            self.style.SUCCESS(
                "Demo: 6 пользователей, 5 категорий, 10 тегов, 20 статей, 30 комментариев, 40 лайков, 15 подписок (на чистой БД)."
            )
        )
